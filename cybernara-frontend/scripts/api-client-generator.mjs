import { createHash } from "node:crypto";

function schemaName(ref) {
  return `${ref.split("/").at(-1)}Schema`;
}

function schemaToZod(schema) {
  if (Array.isArray(schema.type) && schema.type.includes("null")) {
    const nonNullTypes = schema.type.filter((type) => type !== "null");
    const withoutNull = { ...schema, type: nonNullTypes.length === 1 ? nonNullTypes[0] : nonNullTypes };
    return `${schemaToZod(withoutNull)}.nullable()`;
  }

  if (schema.nullable) {
    const withoutNullable = { ...schema };
    delete withoutNullable.nullable;
    return `${schemaToZod(withoutNullable)}.nullable()`;
  }

  if (schema.$ref) {
    return schemaName(schema.$ref);
  }

  if (schema.allOf) {
    return schema.allOf.map(schemaToZod).reduce((left, right) => `z.intersection(${left}, ${right})`);
  }

  if (schema.const !== undefined) {
    return `z.literal(${JSON.stringify(schema.const)})`;
  }

  if (schema.enum) {
    return `z.enum([${schema.enum.map((value) => JSON.stringify(value)).join(", ")}])`;
  }

  if (schema.type === "integer" || schema.type === "number") {
    return "z.number()";
  }

  if (schema.type === "boolean") {
    return "z.boolean()";
  }

  if (schema.type === "array") {
    return `z.array(${schemaToZod(schema.items ?? {})})`;
  }

  if (schema.type === "object" || schema.properties) {
    if (!schema.properties && schema.additionalProperties) {
      return "z.record(z.unknown())";
    }

    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(([key, property]) => {
      const optional = required.has(key) ? "" : ".optional()";
      return `  ${JSON.stringify(key)}: ${schemaToZod(property)}${optional}`;
    });
    return `z.object({\n${fields.join(",\n")}\n})`;
  }

  if (schema.format === "uuid") {
    return "z.string().uuid()";
  }

  if (schema.format === "date-time") {
    return "z.string().datetime()";
  }

  if (schema.type === "string") {
    if (schema.format === "uuid") {
      return "z.string().uuid()";
    }
    if (schema.format === "date-time") {
      return "z.string().datetime()";
    }
    return "z.string()";
  }

  return "z.unknown()";
}

function responseSchemaFor(operation) {
  const okResponse = operation.responses["200"] ?? operation.responses["201"];
  return okResponse?.content?.["application/json"]?.schema;
}

function requestSchemaFor(operation) {
  return operation.requestBody?.content?.["application/json"]?.schema;
}

function pathParams(path) {
  return [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
}

function queryParams(operation) {
  return (operation.parameters ?? []).filter((parameter) => parameter.in === "query");
}

function idempotencyHeader(operation) {
  return (operation.parameters ?? []).find(
    (parameter) => parameter.in === "header" && parameter.name.toLowerCase() === "idempotency-key"
  );
}

function schemaToType(schema) {
  if (schema?.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }

  if (schema?.type === "integer" || schema?.type === "number") {
    return "number";
  }

  if (schema?.type === "boolean") {
    return "boolean";
  }

  return "string";
}

function queryType(parameters) {
  const fields = parameters.map((parameter) => {
    const optional = parameter.required ? "" : "?";
    return `${JSON.stringify(parameter.name)}${optional}: ${schemaToType(parameter.schema)}`;
  });
  return `{\n        ${fields.join(";\n        ")}\n      }`;
}

export function buildClientSource(spec) {
  const contractHash = createHash("sha256").update(JSON.stringify(spec)).digest("hex");
  const schemas = spec.components?.schemas ?? {};
  const lines = [
    "// Generated by scripts/generate-api-client.mjs. Do not edit by hand.",
    'import { z } from "zod";',
    "",
    `export const CONTRACT_SHA256 = ${JSON.stringify(contractHash)};`,
    ""
  ];

  for (const [name, schema] of Object.entries(schemas)) {
    lines.push(`export const ${name}Schema = ${schemaToZod(schema)};`);
    lines.push(`export type ${name} = z.infer<typeof ${name}Schema>;`);
    lines.push("");
  }

  const operations = [];
  const methods = [];
  for (const [routePath, pathItem] of Object.entries(spec.paths)) {
    for (const method of ["get", "post", "put", "patch", "delete"]) {
      const operation = pathItem[method];
      if (!operation) {
        continue;
      }

      const operationId = operation.operationId;
      const params = pathParams(routePath);
      const queryParameters = queryParams(operation);
      const idempotency = idempotencyHeader(operation);
      const responseSchema = responseSchemaFor(operation);
      const requestSchema = requestSchemaFor(operation);
      const responseParser = responseSchema ? schemaToZod(responseSchema) : "z.unknown()";
      const bodyType = requestSchema?.$ref ? `z.infer<typeof ${schemaName(requestSchema.$ref)}>` : "unknown";
      const args = [...params.map((param) => `${param}: string`)];
      if (queryParameters.length > 0) {
        const requiredQuery = queryParameters.some((parameter) => parameter.required);
        args.push(`query${requiredQuery ? "" : "?"}: ${queryType(queryParameters)}`);
      }
      if (requestSchema) {
        args.push(`body: ${bodyType}`);
      }
      if (idempotency) {
        args.push(`options${idempotency.required ? "" : "?"}: { idempotencyKey: string }`);
      }
      const urlExpression = params.reduce(
        (current, param) => current.replace(`{${param}}`, `\${encodeURIComponent(${param})}`),
        routePath
      );
      const bodyLines = requestSchema
        ? [",", "        body: JSON.stringify(body)", "      })"]
        : ["", "      })"];
      const headers = idempotency
        ? '{ "content-type": "application/json", "Idempotency-Key": options.idempotencyKey }'
        : '{ "content-type": "application/json" }';
      const requestUrl = queryParameters.length > 0
        ? `appendQuery(\`\${baseUrl}${urlExpression}\`, query)`
        : `\`\${baseUrl}${urlExpression}\``;

      methods.push(`    async ${operationId}(${args.join(", ")}) {
      const response = await fetcher(${requestUrl}, {
        method: ${JSON.stringify(method.toUpperCase())},
        headers: ${headers}${bodyLines.join("\n")}
      if (!response.ok) {
        throw await buildApiError(${JSON.stringify(operationId)}, response);
      }
      return ${responseParser}.parse(await response.json());
    }`);
      operations.push({ operationId, method: method.toUpperCase(), path: routePath });
    }
  }

  lines.push(`export class CybernaraApiError extends Error {
  constructor(
    public readonly operationId: string,
    public readonly status: number,
    public readonly problem: Problem | null
  ) {
    super(problem?.detail ?? \`\${operationId} failed with \${status}\`);
    this.name = "CybernaraApiError";
  }
}`);
  lines.push("");
  lines.push(`async function buildApiError(operationId: string, response: Response): Promise<CybernaraApiError> {
  const contentType = response.headers.get("content-type") ?? "";
  if (!contentType.includes("json")) {
    return new CybernaraApiError(operationId, response.status, null);
  }

  try {
    return new CybernaraApiError(operationId, response.status, ProblemSchema.parse(await response.json()));
  } catch {
    return new CybernaraApiError(operationId, response.status, null);
  }
}`);
  lines.push("");
  lines.push(`function appendQuery(url: string, query: Record<string, string | number | boolean | undefined> | undefined): string {
  if (!query) {
    return url;
  }

  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(query)) {
    if (value !== undefined) {
      params.set(key, String(value));
    }
  }

  const queryString = params.toString();
  if (!queryString) {
    return url;
  }
  return \`\${url}\${url.includes("?") ? "&" : "?"}\${queryString}\`;
}`);
  lines.push("");
  lines.push("export function createCybernaraClient(baseUrl: string, fetcher: typeof fetch = fetch) {");
  lines.push("  return {");
  lines.push(methods.join(",\n"));
  lines.push("  };");
  lines.push("}");
  lines.push("");
  lines.push(`export const operations = ${JSON.stringify(operations, null, 2)} as const;`);
  lines.push("");

  return `${lines.join("\n")}`;
}
